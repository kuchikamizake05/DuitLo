import {test,expect} from './fixtures';
import {mockReference} from './reference-fixtures';
import { institutions } from '../src/lib/institutions';
for(const theme of ['light','dark'] as const)test(`institution logos and searchable choices ${theme}`,async({page})=>{
 await mockReference(page,theme);await page.addInitScript(()=>localStorage.setItem('fintrack-language','en'));await page.goto('/accounts');
 await expect(page.locator('main img[alt*="BCA"]').first()).toBeVisible();
 await page.goto('/accounts?view=create');
 const editor=page.getByRole('dialog',{name:'Add new account',exact:true});
 await page.locator('[data-reference-node="tambah-akun.49"]').click();
 const banks=page.getByRole('dialog',{name:'Select bank',exact:true});await expect(banks).toBeVisible();
 await expect(banks.locator('button[aria-pressed]')).toHaveCount(institutions.filter(item=>item.kind==='bank').length);
 await expect(banks.getByRole('button',{name:/DANA/})).toHaveCount(0);
 await page.keyboard.press('Escape');
 await editor.locator('[data-reference-node="tambah-akun.45"]').click();
 await page.locator('[data-reference-node="tambah-akun.49"]').click();
 const wallets=page.getByRole('dialog',{name:'Select e-wallet',exact:true});await expect(wallets).toBeVisible();
 await expect(wallets.locator('button[aria-pressed]')).toHaveCount(institutions.filter(item=>item.kind==='ewallet').length);
 await expect(wallets.getByRole('button',{name:/Bank BCA/})).toHaveCount(0);
 await wallets.getByRole('textbox',{name:'Search banks or e-wallets'}).fill('DANA');await wallets.getByRole('button',{name:/DANA/}).click();await expect(wallets).not.toBeVisible();
 await expect(page.locator('[data-reference-node="tambah-akun.51"] img')).toHaveAttribute('src',/\/institutions\/(?:approved\/)?dana(?:-mark)?\.svg/);
 await expect(page.locator('#category-select')).toHaveValue('ewallet');
 await editor.locator('[data-reference-node="tambah-akun.43"]').click();
 await page.locator('[data-reference-node="tambah-akun.49"]').click();await banks.getByRole('textbox',{name:'Search banks or e-wallets'}).fill('Neobank');await banks.getByRole('button',{name:/Bank Neo Commerce/}).click();await expect(page.locator('#category-select')).toHaveValue('bank');
 const logo=page.locator('[data-reference-node="tambah-akun.51"] img');await expect(logo).toHaveAttribute('src',/\/institutions\/(?:approved\/)?bnc\.svg/);expect(await logo.evaluate(img=>getComputedStyle(img).objectFit)).toBe('contain');
});
